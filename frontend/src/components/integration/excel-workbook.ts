function encode(value: string) {
  return new TextEncoder().encode(value);
}

export function buildMigrationWorkbook(layout: MigrationLayout) {
  const layoutRows = [layout.columns.map((column) => column.header), ...layout.exampleRows];
  const instructionRows = [
    [`ANEXSYS · ${layout.title}`],
    [layout.summary],
    ["A linha cinza da aba Layout é exemplo. Apague essas linhas e preencha os dados do sistema antigo. Mantenha o nome das colunas."],
    ["Coluna", "Obrigatório", "Exemplo", "Como preencher"],
    ...layout.columns.map((column) => [column.header, column.required, column.example, column.hint]),
  ];

  return zipStore([
    { name: "[Content_Types].xml", data: encode(CONTENT_TYPES) },
    { name: "_rels/.rels", data: encode(ROOT_RELS) },
    { name: "xl/workbook.xml", data: encode(WORKBOOK) },
    { name: "xl/_rels/workbook.xml.rels", data: encode(WORKBOOK_RELS) },
    { name: "xl/styles.xml", data: encode(STYLES) },
    { name: "xl/worksheets/sheet1.xml", data: encode(sheetXml(layoutRows, true)) },
    { name: "xl/worksheets/sheet2.xml", data: encode(sheetXml(instructionRows, false)) },
  ]);
}

export function downloadMigrationWorkbook(layout: MigrationLayout) {
  const bytes = buildMigrationWorkbook(layout);
  const blob = new Blob([Uint8Array.from(bytes)], {
    type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = layout.fileName;
  document.body.append(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}
